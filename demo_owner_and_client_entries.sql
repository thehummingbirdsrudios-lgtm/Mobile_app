-- -----------------------------------------------------------------------------
-- 1b. FIRST owner of a NEW business: creates the business and makes this login
--     its owner. Run only once per business. This is how Krish was set up.
-- -----------------------------------------------------------------------------
select public.admin_create_tenant(
         'vepari-manufacturer',             -- slug: internal business id; 3–40 chars, lowercase, digits, dashes; unique
         'Vepari Manufacturer (Demo)',      -- business name on bills (owners can rename it in the app)
         (select id from auth.users where email = 'krish@login.vepari.invalid'),   -- the Auth UID (from 1a)
         'krish',                           -- username (same as in the email)
         'Krish')                           -- display name shown in the app
 where not exists (select 1 from public.tenants where slug = 'vepari-manufacturer');

-- -----------------------------------------------------------------------------
-- 1c. MORE partners as owners of the SAME business. This is how Sujal, Savan,
--     Bhaveshbhai and Shaileshbhai were added.
--
--   EDIT for another owner: the (username, display name) row. Create the login
--   with 1a first. Keep 'vepari-manufacturer' so they join OUR business.
-- -----------------------------------------------------------------------------
select public.admin_add_member(
         (select id from public.tenants where slug = 'vepari-manufacturer'),   -- which business (by slug)
         u.id,                              -- the Auth UID, looked up by email
         v.username,
         v.display_name,
         'owner',                           -- role: 'owner' = partner with full access
         '{}')                              -- permissions: leave empty for owners (they have all)
  from (values
    ('sujal', 'Sujal'),
    ('savan', 'Savan'),
    ('bhaveshbhai', 'Bhaveshbhai'),
    ('shaileshbhai', 'Shaileshbhai')
    -- , ('newpartner', 'New Partner')     -- ← EDIT: add a row for another owner
  ) as v(username, display_name)
  join auth.users u on u.email = v.username || '@login.vepari.invalid'
 where not exists (select 1 from public.app_users a where a.id = u.id);

