select a.username, a.display_name, m.role, m.is_active, a.id as auth_uid, b.business_name
  from public.tenant_members m
  join public.app_users a on a.id = m.user_id
  join public.tenants t on t.id = m.tenant_id
  join public.business_profiles b on b.tenant_id = t.id
 where t.slug = 'vepari-manufacturer'
 order by m.role, a.username;


-- #############################################################################
-- 2. CLIENT / CUSTOMER ACCOUNTS
-- #############################################################################
--
-- A client (a jeweller who orders from us) is a row in public.customers that
-- belongs to OUR business. A client has no login, and is never a member.
--
--   client ID  customers.id: generated automatically (uuid). Use it to edit.
--   business   tenant_id: OUR business, looked up by slug. Never another business.
--   name       REQUIRED, 1–120 characters: the client as shown in the app
--   shop_name  optional, up to 120 characters
--   city       optional, up to 60 characters
--   phone, whatsapp_phone  optional, digits only, 10–15 (an optional leading +).
--              Use real numbers only: WhatsApp sharing sends to this number.
--   notes      optional, up to 1000 characters (staff can read them)
--
-- The client's Baki (balance) row is created automatically at 0. Set an opening
-- Baki in the app (Hisaab), never by writing balances or ledger rows here.
-- The two demo clients were created from Krish's login through the app's API
-- (created_by = Krish). Rows added here have no created_by.

-- -----------------------------------------------------------------------------
-- 2a. CREATE clients. EDIT: the rows (name, city, notes).
-- -----------------------------------------------------------------------------
insert into public.customers (tenant_id, name, city, notes)
select t.id, v.name, v.city, v.notes
  from public.tenants t
  cross join (values
    ('Shree Demo Jewellers', 'Demo City', 'DEMO client: fictional test data, not a real business.'),
    ('Royal Test Jewellers', 'Demo City', 'DEMO client: fictional test data, not a real business.')
    -- , ('New Client Jewellers', 'Rajkot', null)   -- ← EDIT: add a row for another client
  ) as v(name, city, notes)
 where t.slug = 'vepari-manufacturer'
   and not exists (select 1 from public.customers c where c.tenant_id = t.id and lower(c.name) = lower(v.name));

-- -----------------------------------------------------------------------------
-- 2b. EDIT a client later (uncomment, edit, run). Clients are archived, never
