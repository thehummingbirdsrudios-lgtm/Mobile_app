-- -----------------------------------------------------------------------------
-- 1a. Create the LOGIN (Auth user + identity).
--
--   EDIT for another owner:  username, password.
--
--   username  3–32 characters: lowercase a–z, digits, '.' or '_', starting with
--             a letter or digit. Must be unique across ALL businesses.
--   email     always <username>@login.vepari.invalid. Not a real mailbox;
--             nothing is ever emailed. Do not change the domain: the app adds it.
--   password  8–72 characters, not the same as the username. Tell it to the
--             person yourself; Vepari never sends it anywhere.
--   Auth UID  generated by Supabase (gen_random_uuid()). NEVER type one in.
--
--   The 5 partners were created with exactly this statement (passwords removed).
-- -----------------------------------------------------------------------------
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token,
    email_change_token_new, email_change, email_change_token_current, phone_change, phone_change_token,
    reauthentication_token, is_sso_user, is_anonymous)
select '00000000-0000-0000-0000-000000000000', gen_random_uuid(), 'authenticated', 'authenticated',
       v.username || '@login.vepari.invalid',
       extensions.crypt(v.password, extensions.gen_salt('bf')),   -- stored as a bcrypt hash, never plain text
       now(),                                                     -- auto-confirmed
       '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '', '', '', '', '', false, false
  from (values
    ('newpartner', '<PASSWORD>')          -- ← EDIT: username, password
  ) as v(username, password)
 where v.password !~ '^<.*>$'                                     -- template guard: placeholder not replaced
   and length(v.password) between 8 and 72
   and lower(v.password) <> v.username
   and v.username ~ '^[a-z0-9][a-z0-9._]{2,31}$'
   and not exists (select 1 from auth.users u where u.email = v.username || '@login.vepari.invalid');

insert into auth.identities (id, provider_id, user_id, identity_data, provider, created_at, updated_at)
select gen_random_uuid(), u.id::text, u.id,
       jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true), 'email', now(), now()
  from auth.users u
 where u.email = 'newpartner@login.vepari.invalid'                -- ← EDIT: same username
   and not exists (select 1 from auth.identities i where i.user_id = u.id and i.provider = 'email');

