-- -----------------------------------------------------------------------------
-- 2c. CHECK: our clients, and that none of them is a login.
-- -----------------------------------------------------------------------------
select c.id as client_id, c.name, c.city, c.archived_at, b.balance_paise
  from public.customers c
  join public.tenants t on t.id = c.tenant_id
  left join public.customer_balances b on b.tenant_id = c.tenant_id and b.customer_id = c.id
 where t.slug = 'vepari-manufacturer'
 order by c.name;

select count(*) as clients_with_a_login     -- must be 0
  from public.app_users a
 where a.display_name in (select name from public.customers);


-- #############################################################################
-- 3. CHECK: owners and clients per business (each business sees only its own)
-- #############################################################################
select t.slug,
       b.business_name,
       (select count(*) from public.tenant_members m where m.tenant_id = t.id and m.role = 'owner') as owners,
       (select count(*) from public.tenant_members m where m.tenant_id = t.id and m.role = 'staff') as staff,
       (select count(*) from public.customers c where c.tenant_id = t.id) as clients
  from public.tenants t
  join public.business_profiles b on b.tenant_id = t.id
 order by t.slug;
